/**
 * Detects the user's browser language and maps to the closest supported G20 language.
 */
export function detectBrowserLanguage(): LanguageCode {
  try {
    const saved = localStorage.getItem('pixelnode_language');
    if (saved && Object.keys(TRANSLATIONS).includes(saved)) {
      return saved as LanguageCode;
    }

    const browserLang = (navigator.language || '').toLowerCase().slice(0, 2);
    if (browserLang && Object.keys(TRANSLATIONS).includes(browserLang)) {
      return browserLang as LanguageCode;
    }
  } catch (err) {
    console.warn('Language detection failed:', err);
  }
  return 'de'; // Default to German or primary
}

export function saveSelectedLanguage(lang: LanguageCode): void {
  try {
    localStorage.setItem('pixelnode_language', lang);
  } catch {}
}
